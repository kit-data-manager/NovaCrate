import { test, expect } from "@playwright/test"

test("guided tour through the editor", async ({ page }) => {
    await page.goto("http://localhost:3000/editor")
    await expect(page.getByText("New to NovaCrate? Take a look")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("The Quickstart menu contains")).toBeVisible()
    await page.getByRole("button", { name: "Quickstart" }).click()
    await expect(page.locator(".react-joyride__spotlight > path").first()).toBeVisible()
    await page.getByRole("menuitem", { name: "Air Quality in Karlsruhe" }).click()
    await expect(page.getByText("The name of the crate you are")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("The Editor menu contains")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("The Crate menu lets you")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("The Entity menu acts on the")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("The global search finds")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("The Entity Editor is where")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("The File Explorer shows the")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("The Entity Graph visualizes")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("For advanced users, the JSON")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("Here you can manage schemas,")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("The Entity Browser lists all")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("This is where you edit the")).toBeVisible()
    await page.getByTestId("button-primary").click()
    await expect(page.getByText("NovaCrate continuously")).toBeVisible()
    await page.getByTestId("button-primary").click()

    const hasAIAssistant = await page.getByText("If you have an API key for").isVisible()
    if (hasAIAssistant) {
        await expect(page.getByText("If you have an API key for")).toBeVisible()
        await page.getByTestId("button-primary").click()
    }

    await expect(page.getByText("All data stays on your device")).toBeVisible()
    await page.getByTestId("button-primary").click()
})
